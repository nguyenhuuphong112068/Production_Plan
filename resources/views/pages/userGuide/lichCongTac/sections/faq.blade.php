<h3>Không kéo được nhân viên vào phòng</h3>
<p>Nhân viên đang nghỉ phép (tên bị gạch), hoặc chưa được cấp phòng đó ở Định Mức › Danh Sách Nhân Viên, hoặc đã có ở phòng đó trong ngày.</p>

<h3>Lịch trực không đúng / thiếu người</h3>
<p>Bấm <b>Đồng bộ</b> để lấy lại lịch trực mới nhất từ eO2. Nếu eO2 không trả được, trang hiện bản lưu gần nhất.</p>

<h3>Tự động phân công để trống một phòng</h3>
<p>Không còn người đi ca có bậc kỹ năng tại phòng đó. Xem báo cáo để biết phòng thiếu, cấp thêm phòng cho nhân viên hoặc xếp tay.</p>
