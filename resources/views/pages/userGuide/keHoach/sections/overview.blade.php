<p>
    Nhóm Kế Hoạch đi từ kế hoạch năm tới từng lô cần sản xuất trong tháng. Chỉ lô của kế hoạch tháng <b>đã gửi</b> mới xuất hiện
    trong danh sách chờ sắp lịch của Lịch Sản Xuất.
</p>

<div class="ug-flow">
    <div class="ug-flow-step"><span class="ug-flow-no">1</span><b>Kế Hoạch Năm</b>Số lô dự kiến từng tháng; đẩy lô sang kế hoạch tháng.</div>
    <div class="ug-flow-step"><span class="ug-flow-no">2</span><b>Kế Hoạch Sản Xuất</b>Tạo kế hoạch tháng, thêm lô, nhập ngày NL/BB, ưu tiên.</div>
    <div class="ug-flow-step"><span class="ug-flow-no">3</span><b>Gửi</b>Phần mềm tạo các công đoạn của từng lô để sắp lịch.</div>
    <div class="ug-flow-step"><span class="ug-flow-no">4</span><b>Phản Hồi KHSX</b>Phản hồi ngày dự kiến KCS, hồ sơ lô, số lệnh.</div>
    <div class="ug-flow-step"><span class="ug-flow-no">5</span><b>Lịch Sản Xuất</b>Sắp lịch các lô đã gửi (xem hướng dẫn Lịch Sản Xuất).</div>
</div>

<p class="mt-3">
    Các màn hình theo dõi (Thẩm Định, Hồ Sơ KCS, Thông Báo Đóng Gói) dùng lại danh sách lô của kế hoạch tháng. Kế hoạch HC-BT
    lập riêng cho thiết bị cần hiệu chuẩn / bảo trì / tiện ích.
</p>
