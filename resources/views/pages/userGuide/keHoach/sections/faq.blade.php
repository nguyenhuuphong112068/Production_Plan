<h3>Lô có trong KHSX nhưng sắp lịch tự động không xếp</h3>
<p>Lô chưa có <b>Ngày có đủ nguyên liệu Pha Chế</b>, hoặc sản phẩm chưa có định mức. Xem thêm hướng dẫn Lịch Sản Xuất › Lỗi thường gặp.</p>

<h3>Đẩy từ KH Năm báo không có kế hoạch tháng nhận</h3>
<p>Phải có kế hoạch tháng <b>chưa gửi</b>. Tạo kế hoạch tháng mới ở Kế Hoạch Sản Xuất rồi đẩy lại.</p>

