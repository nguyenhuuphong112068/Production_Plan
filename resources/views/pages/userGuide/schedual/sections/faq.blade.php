<h3>Thông báo "Đang sắp lịch"</h3>
<p>Một người khác đang chạy sắp lịch tự động cho cùng phân xưởng. Chờ họ chạy xong rồi bấm lại.</p>

<h3>"Một hoặc nhiều sản phẩm chưa được định mức!" / không bấm Chạy được</h3>
<p>
    Có sản phẩm chưa định mức phòng cho một công đoạn. Khai định mức ở <b>Định Mức › Sản Xuất</b>, sau đó mở lại hộp thoại.
</p>

<h3>Có lô không được xếp lịch</h3>
<ul>
    <li>Lô chưa có <b>Ngày có đủ NL</b>.</li>
    <li>Lô được đánh dấu <b>Không sắp lịch tự động</b> (nút <i class="fas fa-calendar-times"></i> trên danh sách KHSX).</li>
    <li>Công đoạn sau của lô đã bắt đầu chạy: công đoạn trước còn thiếu lịch được bỏ qua.</li>
    <li>Công đoạn đó nằm sau công đoạn cuối đã chọn trên dải bước (ví dụ chọn <b>ĐH</b> thì Bao phim, Đóng gói không được xếp).</li>
    <li>Lô đã có lịch: sắp lịch tự động không xếp lại lô đã có lịch. Xoá lịch bằng <span class="ug-emoji">🗑️</span> trước.</li>
</ul>

<h3>Lô cần hàng muộn lại chạy trước lô cần hàng sớm</h3>
<p>
    Sắp lịch tự động xếp tiến: lô nhóm ưu tiên cao hơn chọn phòng trước, lô nhóm sau lấp khoảng trống - kể cả khoảng
    trống sớm. Xem <a href="#thu-tu-uu-tien">Thứ tự ưu tiên</a> và <a href="#chon-phong-gio">Cách chọn phòng</a>. Muốn
    giãn đầu nguồn để bớt tồn, dùng <a href="#kiem-soat-ton-btp">Kiểm soát tồn BTP</a>.
</p>

<h3>Đổi thời gian chờ kiểm nghiệm trên hộp thoại mà lịch không đổi</h3>
<p>
    Hiện các ô thời gian chờ chưa có tác dụng; phần mềm luôn dùng giá trị mặc định đang hiện (lô thẩm định THT 1 ngày,
    ĐH / BP / ĐG 5 ngày; lô thương mại 0 ngày).
</p>

<h3>Lịch có chồng giờ / vệ sinh đè lô sau sau khi chạy</h3>
<p>
    Lịch cũ có thể đã chồng giờ từ trước (sắp lịch tự động không sửa lịch đã có). Ngoài ra lô lẻ chèn sát trước một chiến
    dịch đôi khi có lịch vệ sinh kéo qua ngày nghỉ, lấn sang lô kế tiếp. Lô bị tô màu vàng (vệ sinh) hoặc xám đen (sai
    thứ tự) cần chỉnh tay rồi lưu.
</p>

