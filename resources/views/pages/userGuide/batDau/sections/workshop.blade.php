<p>
    Phần lớn dữ liệu (phòng, kế hoạch, lịch, nhân sự...) được lọc theo <b>phân xưởng đang chọn</b>. Mục đầu tiên trên menu trái
    hiện tên phân xưởng đang chọn; bấm vào để đổi.
</p>
<ol class="ug-steps">
    <li>Bấm tên phân xưởng ở đầu menu trái.</li>
    <li>Chọn <b>PXV1</b>, <b>PXV2</b>, <b>PXVH</b>, <b>PXN</b> hoặc <b>PXDN</b>. Phần mềm tải lại đúng màn hình đang xem với dữ liệu của phân xưởng mới.</li>
</ol>
<div class="ug-callout is-warn">
    <i class="fas fa-exclamation-triangle"></i>
    <div>Xem được phân xưởng khác không có nghĩa là sửa được: nhiều chức năng (ví dụ sửa lịch sản xuất) chỉ cho sửa khi phân
        xưởng đang chọn trùng phòng ban của tài khoản. Khi đăng nhập lại, phân xưởng trở về theo phòng ban của tài khoản.</div>
