<h3>Không đăng nhập được</h3>
<p>Đọc câu báo trên trang đăng nhập và đối chiếu bảng ở mục <a href="#dang-nhap">Đăng nhập</a>. Bị khoá do nhập sai thì chờ hết
    thời gian khoá; tài khoản bị vô hiệu hoá thì liên hệ quản trị.</p>

<h3>Đang làm thì bị đưa về trang đăng nhập</h3>
<p>Phiên đã hết do không thao tác quá {{ config('session.lifetime') }} phút. Đăng nhập lại; dữ liệu chưa bấm lưu cần nhập lại.</p>

<h3>Không thấy một nhóm menu / một màn hình</h3>
<p>Tài khoản chưa được cấp quyền. Quản trị cấp quyền theo nhóm ở <b>User Policy › Nhóm Phân Quyền</b>.</p>

<h3>Dữ liệu trống hoặc khác đồng nghiệp</h3>
<p>Kiểm tra phân xưởng đang chọn ở đầu menu trái (<a href="#phan-xuong">Chọn phân xưởng</a>): mỗi phân xưởng có dữ liệu riêng.</p>

<h3>Thấy được nhưng không sửa được</h3>
<p>Nhiều chức năng chỉ cho sửa với nhóm quyền nhất định hoặc khi phân xưởng đang chọn trùng phòng ban của tài khoản. Xem mục
    Quyền trong tài liệu hướng dẫn của nhóm chức năng đó.</p>
