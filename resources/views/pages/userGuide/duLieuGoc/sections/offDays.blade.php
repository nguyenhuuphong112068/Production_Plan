    lúc 05:30, cho <b>6 tháng tới</b> tính từ hôm đó. Màn hình <i>Cập nhật ngày nghỉ</i> trước đây trong Dữ Liệu Gốc đã bỏ.
</p>

<h3>Ngày nào được tính là ngày nghỉ</h3>
<ul>
    <li>Các ngày eO2 đánh dấu là ngày nghỉ: nghỉ lễ, Tết, thứ Bảy nghỉ luân phiên, ngày nghỉ công ty.</li>
    <li><b>Mọi Chủ nhật</b>, kể cả Chủ nhật eO2 ghi là đi làm bù. Đây là quy tắc chung của PMS.</li>
</ul>
<p>
    Lịch nghỉ giống nhau ở mọi phòng ban. Ngày đã qua được giữ nguyên làm lịch sử, chỉ các ngày từ hôm nay trở đi được cập
    nhật theo eO2: ngày eO2 bỏ nghỉ (chuyển thành ngày làm) sẽ được gỡ khỏi lịch nghỉ, ngày eO2 thêm nghỉ sẽ được thêm vào.
</p>

<h3>Ngày nghỉ được dùng ở đâu</h3>
<ul>
    <li>Được chọn sẵn trong ô <i>Ngày không sắp lịch</i> của hộp thoại Sắp lịch tự động: lô không bắt đầu trong ngày nghỉ.</li>
    <li>Tô nền ngày nghỉ trên Lịch Sản Xuất Chart và Lịch Công Tác.</li>
    <li>Loại khỏi phép đếm ngày làm việc (hồ sơ KCS, ngày nhận bao bì, báo cáo).</li>
</ul>

