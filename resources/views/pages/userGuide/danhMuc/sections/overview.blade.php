<p>
    Nhóm <b>Danh Mục</b> khai báo sản phẩm theo đúng cấp sản xuất: <b>Bán Thành Phẩm</b> (BTP, mã BMR - từ cân tới bao phim)
    và <b>Thành Phẩm</b> (TP, mã BPR - đóng gói theo thị trường, qui cách). Một BTP có thể có nhiều TP. Kế hoạch sản xuất,
    định mức và lịch đều chọn lại các mã ở đây.
</p>

