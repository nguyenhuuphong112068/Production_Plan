    <div class="ug-flow-step"><span class="ug-flow-no">3</span><b>Thành Phẩm</b>Mã TP gắn với một mã BTP, thị trường, qui cách.</div>
    <div class="ug-flow-step"><span class="ug-flow-no">4</span><b>Định Mức</b>Phòng và thời gian sản xuất từng công đoạn.</div>
</div>

