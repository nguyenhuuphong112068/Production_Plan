<h3>"Thời gian ... phải đúng định dạng HH:mm (phút là 00, 15, 30 hoặc 45)"</h3>
<p>Nhập giờ:phút, phút chỉ được 00, 15, 30, 45 (lịch chia theo bước 15 phút). Ví dụ 1 giờ 20 phút → nhập 01:15 hoặc 01:30.</p>

<h3>Sản phẩm không hiện trong danh sách định mức của công đoạn</h3>
<p>Danh mục BTP / TP của mã chưa tick công đoạn đó (Danh Mục › Bán Thành Phẩm, mục Công Đoạn Bao Gồm), hoặc mã thuộc phân xưởng khác.</p>

<h3>Không thêm được phòng cho nhân viên</h3>
<p>Phòng đã được gán cho nhân viên đó, hoặc mọi phòng của tổ đã được gán hết.</p>
